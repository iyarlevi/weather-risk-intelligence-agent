"""HTTP API. The chat UI (and anyone else) talks to the agent through these endpoints.

Run:   uv run uvicorn app.api.main:app --reload
Docs:  http://localhost:8000/docs  (interactive, generated by FastAPI)

Endpoints:
  POST   /chat                  ask the agent (pass session_id back for follow-ups)
  DELETE /chat/{session_id}     forget a conversation
  GET    /hubs                  hub list (optional ?region=)
  GET    /hubs/{hub}/risk       full deterministic score breakdown for one hub
  GET    /rankings              ranking by composite or one hazard (?hazard=&region=&limit=)
  GET    /methodology           weights, scales, limitations
  GET    /health                data loaded? API key configured?

The /hubs, /rankings and /methodology endpoints never call the LLM. They return the
deterministic model directly, which keeps them fast and free, and lets the UI show tables.
"""

from __future__ import annotations

import logging
import sqlite3
from collections.abc import Iterator
from contextlib import asynccontextmanager
from functools import lru_cache
from pathlib import Path
from typing import Annotated

import anthropic
from fastapi import Depends, FastAPI, HTTPException, Query
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel, Field

from app.agent import tools
from app.agent.agent import AgentError, AgentResponse, WeatherRiskAgent
from app.agent.schemas import RankBy, Region
from app.config import ROOT, get_hub, get_settings, load_hubs
from app.data_sources.ingest import history_window
from app.scoring.engine import config_fingerprint, rank
from app.scoring.models import HubRisk, RankingEntry
from app.storage import db

log = logging.getLogger("wria.api")
WEB_DIR = ROOT / "web"


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Warm-up: score every hub once at startup, so the first chat isn't slow and missing
    # data shows up in the logs immediately instead of mid-conversation.
    conn = db.connect()
    rows = conn.execute("SELECT COUNT(*) FROM weather_daily").fetchone()[0]
    if rows == 0:
        log.warning("No weather data. Run: uv run python -m app.data_sources.ingest")
    tools.SCORES.get(conn)
    conn.close()
    yield


app = FastAPI(
    title="Weather Risk Intelligence Agent",
    description="Ranks and explains weather disruption risk for US distribution hubs.",
    version="0.1.0",
    lifespan=lifespan,
)


# ------------------------------------------------------------------- dependencies


def get_conn() -> Iterator[sqlite3.Connection]:
    """One SQLite connection per request (connections shouldn't be shared across threads)."""
    conn = db.connect()
    try:
        yield conn
    finally:
        conn.close()


@lru_cache
def _anthropic_client() -> anthropic.Anthropic:
    # Created once and shared: the client holds an HTTP connection pool and is thread-safe.
    return anthropic.Anthropic(api_key=get_settings().anthropic_api_key or None)


# Annotated aliases: FastAPI injects these per request (the modern style for dependencies).
Conn = Annotated[sqlite3.Connection, Depends(get_conn)]


def get_agent(conn: Conn) -> WeatherRiskAgent:
    return WeatherRiskAgent(conn=conn, client=_anthropic_client())


Agent = Annotated[WeatherRiskAgent, Depends(get_agent)]


# ------------------------------------------------------------------------- models


class ChatRequest(BaseModel):
    message: str = Field(min_length=1, max_length=2000, examples=["Why is Dallas high risk?"])
    session_id: str | None = Field(
        None, max_length=64, description="Omit to start a new conversation"
    )


class HealthResponse(BaseModel):
    status: str
    hubs: int
    weather_days: int
    fema_counties: int
    history_window: str
    scoring_config: str
    llm_configured: bool


# ----------------------------------------------------------------------- endpoints


@app.post("/chat", response_model=AgentResponse, tags=["agent"])
def chat(req: ChatRequest, agent: Agent) -> AgentResponse:
    """Ask the agent a question. Returns the structured answer plus the tools it used."""
    try:
        return agent.chat(req.message.strip(), req.session_id)
    except AgentError as exc:
        # 502: an upstream problem (LLM API, refusal, bad output), not the caller's fault.
        raise HTTPException(status_code=502, detail=str(exc)) from exc


@app.delete("/chat/{session_id}", status_code=204, tags=["agent"])
def reset_chat(session_id: str, conn: Conn) -> None:
    db.delete_session(conn, session_id)


@app.get("/hubs", tags=["data"])
def list_hubs(region: Region | None = None) -> list[dict]:
    return [h.model_dump() for h in load_hubs() if not region or h.region == region]


@app.get("/hubs/{hub}/risk", response_model=HubRisk, tags=["data"])
def hub_risk(hub: str, conn: Conn) -> HubRisk:
    h = get_hub(hub)
    if h is None:
        raise HTTPException(status_code=404, detail=f"Unknown hub '{hub}'")
    return tools.SCORES.get(conn)[h.id]


@app.get("/rankings", response_model=list[RankingEntry], tags=["data"])
def rankings(
    conn: Conn,
    hazard: RankBy = "composite",
    region: Region | None = None,
    limit: Annotated[int | None, Query(ge=1, le=50)] = None,
) -> list[RankingEntry]:
    return rank(
        tools.SCORES.get(conn),
        hazard=None if hazard == "composite" else hazard,
        region=region,
        limit=limit,
    )


@app.get("/methodology", tags=["data"])
def methodology(conn: Conn) -> dict:
    return tools.get_methodology(conn, tools.s.NoInput())


@app.get("/health", response_model=HealthResponse, tags=["ops"])
def health(conn: Conn) -> HealthResponse:
    weather = conn.execute("SELECT COUNT(*) FROM weather_daily").fetchone()[0]
    fema = conn.execute("SELECT COUNT(*) FROM nri_county").fetchone()[0]
    start, end = history_window()
    return HealthResponse(
        status="ok" if weather and fema else "no_data",
        hubs=len(load_hubs()),
        weather_days=weather,
        fema_counties=fema,
        history_window=f"{start}..{end}",
        scoring_config=config_fingerprint(),
        llm_configured=bool(get_settings().anthropic_api_key),
    )


# ------------------------------------------------------------------- chat UI (stage 6)

# Serve the static chat UI from /web if it exists. The UI is just a client of the API above.
if (WEB_DIR / "index.html").exists():
    app.mount("/static", StaticFiles(directory=WEB_DIR), name="static")

    @app.get("/", include_in_schema=False)
    def index() -> FileResponse:
        return FileResponse(Path(WEB_DIR) / "index.html")
